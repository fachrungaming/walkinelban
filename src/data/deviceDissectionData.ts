export function getDeviceDissectionBlueprint(componentId: string): DeviceDissectionBlueprint {
  if (BESPOKE_BLUEPRINTS[componentId]) {
    return BESPOKE_BLUEPRINTS[componentId];
  }
  const comp = COMPONENT_MAP[componentId];
  if (comp) {
    return buildGenericBlueprint(comp);
  }
  return BESPOKE_BLUEPRINTS['comp-pas-aas'];
}

export function computeDeviceDissectionTelemetry(
  blueprint: DeviceDissectionBlueprint,
  params: DissectionSimParams,
  activeFaultIds: string[]
): Record<string, DissectionPartTelemetry> {
  const result: Record<string, DissectionPartTelemetry> = {};
  const activeFaults = blueprint.faults.filter((f) => activeFaultIds.includes(f.id));
  const workloadScale = 0.55 + (params.workloadPercent / 100) * 0.75;
  const ambientDelta = params.ambientTempC - 23;

  for (const part of blueprint.parts) {
    const partFaults = activeFaults.filter((f) => f.affectedPartIds.includes(part.id));
    const hasFault = partFaults.length > 0;
    const tempBoost = partFaults.reduce((acc, f) => acc + f.tempDeltaC, 0);
    const loadBoost = partFaults.reduce((acc, f) => acc + f.loadDelta, 0);

    const loadPercent = Math.max(
      0,
      Math.min(100, Math.round(part.baseLoadPercent * workloadScale + loadBoost))
    );
    const tempC = Math.round(
      part.baseTempC + ambientDelta + (params.workloadPercent - 45) * 0.14 + tempBoost
    );

    const status: 'NOMINAL' | 'WARNING' | 'FAULT' = hasFault
      ? 'FAULT'
      : tempC >= 55 || loadPercent >= 88
        ? 'WARNING'
        : 'NOMINAL';

    result[part.id] = {
      part,
      status,
      loadPercent,
      tempC,
      metric3Value: hasFault ? part.metric3Fault : part.metric3Nominal,
      metric4Value: hasFault ? part.metric4Fault : part.metric4Nominal,
    };
  }

  return result;
}
